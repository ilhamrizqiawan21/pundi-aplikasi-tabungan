// Palet warna cerah avatar dari Mockup Pundi
const AVATAR_PALETTE = [
  { bg: '#2563EB', text: '#FFFFFF' }, // Blue (AN)
  { bg: '#059669', text: '#FFFFFF' }, // Emerald (MR)
  { bg: '#7C3AED', text: '#FFFFFF' }, // Purple (SK)
  { bg: '#D97706', text: '#FFFFFF' }, // Amber (FA)
  { bg: '#DB2777', text: '#FFFFFF' }, // Pink (NP)
  { bg: '#0284C7', text: '#FFFFFF' }, // Cyan (ZS)
  { bg: '#4F46E5', text: '#FFFFFF' }, // Indigo
  { bg: '#EA580C', text: '#FFFFFF' }, // Orange
];

export function getAvatarColor(name: string) {
  let hash = 0;
  for (let i = 0; i < name.length; i++) {
    hash = (hash << 5) - hash + name.charCodeAt(i);
    hash |= 0;
  }
  const index = Math.abs(hash) % AVATAR_PALETTE.length;
  return AVATAR_PALETTE[index];
}

export function getInitials(name: string): string {
  const parts = name.trim().split(/\s+/).filter(Boolean);
  if (parts.length === 0) return 'S';
  if (parts.length === 1) return parts[0].slice(0, 2).toUpperCase();
  return (parts[0][0] + parts[parts.length - 1][0]).toUpperCase();
}

export function StudentAvatar({
  name,
  size = 36,
  fontSize = 13,
  border,
}: {
  name: string;
  size?: number;
  fontSize?: number;
  border?: string;
}) {
  const colors = getAvatarColor(name);
  const initials = getInitials(name);

  return (
    <div
      style={{
        width: `${size}px`,
        height: `${size}px`,
        borderRadius: '9999px',
        backgroundColor: colors.bg,
        color: colors.text,
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'center',
        fontWeight: 700,
        fontSize: `${fontSize}px`,
        flexShrink: 0,
        border: border || 'none',
        userSelect: 'none',
        letterSpacing: '0.5px',
      }}
    >
      {initials}
    </div>
  );
}
